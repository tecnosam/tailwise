"""Runs the Tailwise binary for a benchmark run.

The generated config keeps every decision deterministic and local: no random
floor, no exporters, the OTLP receivers off (the bench scores through the
synchronous OTLP endpoint), and the API on loopback. The Jev key comes from
envchain or the environment and is never written or logged here.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import time
from pathlib import Path
from types import TracebackType
from typing import IO
from urllib.parse import urlparse

import httpx
import yaml

from .config import Config


def version(binary: Path) -> str:
    out = subprocess.run([str(binary), "-version"], capture_output=True, text=True, timeout=10)
    return out.stdout.strip().removeprefix("tailwise ").strip() or out.stderr.strip()


def write_config(cfg: Config, path: Path) -> None:
    url = urlparse(cfg.tailwise.url)
    scorer: dict[str, object] = {"model": cfg.tailwise.model, "system_prompt": cfg.tailwise.system_prompt,
                                 "evidence": cfg.tailwise.evidence, "evidence_budget": cfg.tailwise.evidence_budget}
    if cfg.tailwise.manifest:
        scorer["manifest"] = str(cfg.resolve(cfg.tailwise.manifest))
    doc = {
        "server": {"addr": f"{url.hostname}:{url.port or 80}"},
        "otlp": {"grpc_addr": "", "http_addr": ""},
        "scorer": scorer,
        "policy": {"keep_threshold": cfg.tailwise.keep_threshold, "random_floor": 0},
        "exporters": [],
    }
    path.write_text("# Generated by the benchmark harness for one run.\n" + yaml.safe_dump(doc, sort_keys=False))


class Tailwise:
    """A Tailwise process, started and stopped with the run (unless
    tailwise.start is false, when an already running one is used)."""

    def __init__(self, cfg: Config, run_dir: Path) -> None:
        self.cfg = cfg
        self.run_dir = run_dir
        self.binary = cfg.resolve(cfg.tailwise.binary)
        self._proc: subprocess.Popen[bytes] | None = None
        self._log: IO[bytes] | None = None

    def __enter__(self) -> Tailwise:
        if self.cfg.tailwise.start:
            self._start()
        self._wait_ready()
        return self

    def __exit__(self, t: type[BaseException] | None, e: BaseException | None, tb: TracebackType | None) -> None:
        if self._proc is not None:
            self._proc.terminate()
            try:
                self._proc.wait(timeout=30)
            except subprocess.TimeoutExpired:
                self._proc.kill()
        if self._log is not None:
            self._log.close()

    def _start(self) -> None:
        if not self.binary.exists():
            raise SystemExit(f"{self.binary} not found: run `make build` in the repository root")
        conf = self.run_dir / "tailwise.yaml"
        write_config(self.cfg, conf)
        cmd = [str(self.binary), "-config", str(conf)]
        if self.cfg.tailwise.envchain:
            if not shutil.which("envchain"):
                raise SystemExit("tailwise.envchain is set but envchain is not installed")
            cmd = ["envchain", self.cfg.tailwise.envchain, *cmd]
        elif not os.environ.get("JEV_API_KEY"):
            raise SystemExit("JEV_API_KEY is not set (or set tailwise.envchain)")
        self._log = (self.run_dir / "tailwise.log").open("wb")
        self._proc = subprocess.Popen(cmd, stdout=self._log, stderr=subprocess.STDOUT)

    def _wait_ready(self, timeout: float = 60) -> None:
        deadline = time.monotonic() + timeout
        last = ""
        while time.monotonic() < deadline:
            if self._proc is not None and self._proc.poll() is not None:
                raise SystemExit(f"Tailwise exited with {self._proc.returncode}; see {self.run_dir / 'tailwise.log'}")
            try:
                r = httpx.get(self.cfg.tailwise.url + "/readyz", timeout=5)
                if r.status_code == 200:
                    return
                last = r.text
            except httpx.TransportError as e:
                last = str(e)
            time.sleep(0.5)
        raise SystemExit(f"Tailwise at {self.cfg.tailwise.url} was not ready after {timeout:.0f}s: {last}")
